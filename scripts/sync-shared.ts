/**
 * Copies the shared reader into every plugin, because a hooks module may only
 * import files inside its own plugin directory:
 *
 *   shared/lib/      -> plugins/<name>/hooks/lib/strikethroo/
 *   shared/testing/  -> plugins/<name>/tests/lib/strikethroo/
 *
 * It also writes shared/tests/fixture-files.ts from shared/fixtures/, since
 * tests can only import code files.
 *
 * Usage: node scripts/sync-shared.ts [--check]
 * With --check it writes nothing and exits 1 when any copy is out of date.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { plugins, ROOT } from './plugins.ts'

const isCheck = process.argv.includes('--check')

/** Every file under `dir`, as paths relative to it, sorted. */
const filesUnder = (dir: string): string[] =>
  existsSync(dir)
    ? readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter(entry => entry.isFile())
        .map(entry => relative(dir, join(entry.parentPath, entry.name)).split('\\').join('/'))
        .sort()
    : []

const FIXTURES = join(ROOT, 'shared/fixtures')
const isTestFixture = (path: string): boolean =>
  path === 'serve-workspace/.init-metadata.json' || path.startsWith('serve-workspace/archive/')

const fixtureModule = (): string => {
  const entries = filesUnder(FIXTURES)
    .filter(isTestFixture)
    .map(path => `  ${JSON.stringify(path)}: ${JSON.stringify(readFileSync(join(FIXTURES, path), 'utf8'))},`)
  return [
    '// Generated by `node scripts/sync-shared.ts` from shared/fixtures/. Do not edit.',
    'export const FIXTURE_FILES: Readonly<Record<string, string>> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
}

/** Each target directory and the files it must hold exactly. */
const targets = (): Map<string, Map<string, string>> => {
  const copyOf = (source: string): Map<string, string> =>
    new Map(filesUnder(join(ROOT, source)).map(path => [path, readFileSync(join(ROOT, source, path), 'utf8')]))
  const lib = copyOf('shared/lib')
  const testing = copyOf('shared/testing')
  const result = new Map<string, Map<string, string>>()
  for (const plugin of plugins()) {
    result.set(join(plugin.dir, 'hooks/lib/strikethroo'), lib)
    result.set(join(plugin.dir, 'tests/lib/strikethroo'), testing)
  }
  return result
}

const stale: string[] = []
const write = (path: string, text: string): void => {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return
  stale.push(relative(ROOT, path))
  if (isCheck) return
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}

write(join(ROOT, 'shared/tests/fixture-files.ts'), fixtureModule())
for (const [dir, files] of targets()) {
  for (const [path, text] of files) write(join(dir, path), text)
  for (const path of filesUnder(dir).filter(path => !files.has(path))) {
    stale.push(relative(ROOT, join(dir, path)))
    if (!isCheck) rmSync(join(dir, path))
  }
}

if (stale.length === 0) console.log('sync-shared: every copy matches shared/')
else if (isCheck) {
  console.error(`sync-shared: out of date; run npm run sync:\n  ${stale.join('\n  ')}`)
  process.exit(1)
} else console.log(`sync-shared: updated\n  ${stale.join('\n  ')}`)
